// Slide 04: Estrutura básica de uma função
// Palavra function + nome + parênteses + bloco
function nomeDaFuncao() {
    // Instruções executadas quando a função for chamada
    console.log('Função nomeDaFuncao executada com sucesso!');
}

// A declaração cria a função.
// A chamada executa a função.
nomeDaFuncao();

// Declarar não executa. Os parênteses na chamada iniciam a execução.
