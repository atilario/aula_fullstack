// Slide 31 - Exercício 3:
// Crie calcularArea(base, altura) e retorne a área do retângulo.

function calcularArea(base, altura) {
    return base * altura;
}

// Exemplos de chamada e exibição:
const area1 = calcularArea(5, 10);
console.log(`Área (base: 5, altura: 10): ${area1}`); // 50

const area2 = calcularArea(7.5, 4);
console.log(`Área (base: 7.5, altura: 4): ${area2}`); // 30
